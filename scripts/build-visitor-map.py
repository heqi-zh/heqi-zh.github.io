#!/usr/bin/env python3
"""Build the Asia/Pacific-centred visitor map from Natural Earth country GeoJSON.

Usage: python3 scripts/build-visitor-map.py /path/to/ne_110m_admin_0_countries.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_admin_0_countries.geojson
Natural Earth data is public domain. Projection matches assets/js/visitor-map.js.
"""
import json
import math
import sys
from pathlib import Path

CENTRE = 150
SCALE = 150
WEST, EAST = CENTRE - 180, CENTRE + 180
SOUTH, NORTH = -60, 85


def project(lon, lat):
    return (500 + SCALE * math.radians(lon - CENTRE),
            380 - SCALE * math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


def clip(points, axis, boundary, keep_above):
    result = []
    for previous, current in zip(points[-1:] + points[:-1], points):
        before = previous[axis] >= boundary if keep_above else previous[axis] <= boundary
        after = current[axis] >= boundary if keep_above else current[axis] <= boundary
        if before != after:
            t = (boundary - previous[axis]) / (current[axis] - previous[axis])
            result.append(tuple(previous[i] + t * (current[i] - previous[i]) for i in (0, 1)))
        if after:
            result.append(current)
    return result


def ring_paths(ring):
    # Unwrap before clipping: countries crossing the dateline must stay intact.
    points = []
    for lon, lat, *_ in ring:
        if points:
            lon += 360 * round((points[-1][0] - lon) / 360)
        points.append((lon, lat))
    for offset in (-360, 0, 360):
        clipped = [(lon + offset, lat) for lon, lat in points]
        for axis, edge, above in ((0, WEST, True), (0, EAST, False),
                                  (1, SOUTH, True), (1, NORTH, False)):
            clipped = clip(clipped, axis, edge, above)
            if not clipped:
                break
        if len(clipped) >= 3:
            yield 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in map(lambda p: project(*p), clipped)) + 'Z'


source = json.loads(Path(sys.argv[1]).read_text())
svg = ['<!-- Natural Earth public-domain country polygons; Asia/Pacific-centred Mercator.',
       '     Generated by scripts/build-visitor-map.py; source URL is recorded there. -->']
for feature in source['features']:
    if feature['properties']['ADMIN'] == 'Antarctica':
        continue
    geometry = feature['geometry']
    polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    segments = [part for polygon in polygons for ring in polygon for part in ring_paths(ring)]
    if segments:
        svg.append('<path d="' + ''.join(segments) + '"/>')
Path('_includes/visitor-map-countries.svg').write_text('\n'.join(svg) + '\n')
